// Generated display bundle only. Canonical inputs remain JSON and the receipt.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
const here=path.dirname(fileURLToPath(import.meta.url));
const read=name=>JSON.parse(fs.readFileSync(path.join(here,name),'utf8').replace(/^\uFEFF/,''));
const config=read('home.config.json'), examples=read('examples.json');
if(config.version!==1 || !Array.isArray(config.profiles))throw Error('Invalid Home config');
const ids=new Set();
for(const profile of config.profiles){
  if(!profile.id || ids.has(profile.id))throw Error('Duplicate/missing profile ID');
  ids.add(profile.id);
  const modules=new Set();
  for(const module of profile.modules || []){
    if(!['wants','results','compare','maintenance'].includes(module.type) || modules.has(module.id))throw Error('Unknown/duplicate module');
    modules.add(module.id);
  }
  if(profile.source!=='ene' && !examples[profile.source])throw Error('Example source missing');
}
let assessment=null;
const receipt=path.join(here,'..',config.profiles.find(p=>p.source==='ene')?.preview?.receipt||'receipts/NO_CURRENT_RECEIPT.md');
if(fs.existsSync(receipt)){
  const match=fs.readFileSync(receipt,'utf8').match(/```ene-assessment\s*\n([\s\S]*?)\n```/);
  if(match)assessment=JSON.parse(match[1]);
}
// Document contents are display snapshots of existing files, not separately maintained facts.
const root=path.resolve(here,'..'),current=JSON.parse(fs.readFileSync(path.join(root,'results/CURRENT.json'),'utf8'));
const recent=['docs/USER_GUIDE.md','results/README.md',current.currentChange?.contract,current.receipt,current.accepted_baseline?.receipt].filter(Boolean);
const rules=['README.md','ENE_BASE_V1_FREEZE.md','docs/ENE_PARADIGM.md','00_START_HERE.md','AGENTS.md','CODEX_CONTROLLER_CONTRACT.md','BUILDER_CONTRACT.md','V1_FREEZE.md','V1_1_FREEZE.md','V1_1_CLARIFICATIONS.md','V1_1_INTEGRATION_REPORT.md','EVENT_PROTOCOL.md','APPLY_TO_EXISTING_PROJECT.md'];
const documentRoots=config.document_sources?.history_roots||['changes/active','changes/done','receipts'];
function collect(dir){
  if(!/^(?:changes\/(?:active|done)|receipts|docs)(?:\/[a-zA-Z0-9_\-\u4e00-\u9fff]+)*$/.test(dir))throw Error('Document root outside the agreed document directories: '+dir);
  const absolute=path.join(root,dir);
  if(!fs.existsSync(absolute))return [];
  if(fs.lstatSync(absolute).isSymbolicLink())throw Error('Document directory must not be a symlink: '+dir);
  return fs.readdirSync(absolute,{withFileTypes:true}).sort((a,b)=>a.name.localeCompare(b.name)).flatMap(entry=>{
    if(entry.name.startsWith('.')||entry.isSymbolicLink()||/STORYFLOW|RESEARCH|EIADS/i.test(entry.name))return [];
    const relative=dir+'/'+entry.name;
    return entry.isDirectory()?collect(relative):entry.isFile()&&entry.name.endsWith('.md')?[relative]:[];
  });
}
const history=documentRoots.flatMap(collect);
const seen=new Set(),documents=[];
for(const [group,paths] of [['current',recent],['rules',rules],['history',history]])for(const relative of paths){
  if(seen.has(relative)||!fs.existsSync(path.join(root,relative)))continue;
  if(path.isAbsolute(relative)||relative.split(/[\\/]/).some(part=>part==='..'||part.startsWith('.')))throw Error('Invalid document path');
  const actual=fs.realpathSync(path.join(root,relative)),within=path.relative(fs.realpathSync(root),actual);
  if(within.startsWith('..')||path.isAbsolute(within))throw Error('Document outside project');
  seen.add(relative);const body=fs.readFileSync(actual,'utf8').replace(/^\uFEFF/,'');
  documents.push({group,path:relative,title:body.match(/^#\s+(.+)$/m)?.[1]?.trim()||relative,text:body});
}
// Rebuild earliest observable saves from Git; never invent item creation dates from file mtime or IDs.
const firstSaved={};
try {
  const commits=execFileSync('git',['-C',root,'log','--reverse','--format=%H%x09%cI','--','WANT.json'],{encoding:'utf8',windowsHide:true}).trim().split('\n').filter(Boolean);
  let order=0;
  for(const line of commits){
    const [commit,time]=line.trim().split('\t');
    const snapshot=JSON.parse(execFileSync('git',['-C',root,'show',commit+':WANT.json'],{encoding:'utf8',windowsHide:true}).replace(/^\uFEFF/,''));
    for(const item of snapshot.items||[])if(!firstSaved[item.id])firstSaved[item.id]={time,commit,order:order++};
  }
}catch{console.warn('Some Git record dates unavailable; unknown dates remain unknown.');}
const data={config,examples,assessment,documents,first_saved:firstSaved,readme:fs.readFileSync(path.join(here,'README.md'),'utf8')};
fs.writeFileSync(path.join(here,'config-data.js'),'// Generated by refresh.mjs. Do not edit.\nwindow.ENE_HOME_CONFIG = '+JSON.stringify(data).replace(/</g,'\\u003c')+';\n');
console.log('ENE Home display bundle refreshed');
